/* Builds the German, Russian and Ukrainian homepages from index.html.
 *
 *   node build-i18n.mjs
 *
 * index.html stays the single source of truth: markup, styles and script are
 * written once, in English, and each language version is that same file with
 * its text swapped, its paths re-rooted and a translation blob injected for the
 * strings the page builds at runtime.
 *
 * Nothing here invents markup. If a block the build expects to find has moved,
 * it throws rather than writing a page that is half translated.
 */
import fs from 'fs';
import path from 'path';
import { LANGS, SITE, byCode, urlFor, outPath } from './i18n/config.mjs';
import { localizePage } from './i18n/localize.mjs';
import { loadMap, loadUi } from './i18n/load.mjs';
import { langPicker } from './i18n/picker.mjs';

const home = fs.readFileSync('index.html', 'utf8');
const url = (code) => urlFor(code, 'index.html');

/* The picker in the source file is the English one; each version gets its own,
   with the current language marked and the button showing its code. It is
   swapped as a protected block so the string walk never sees the language
   names — they are the same in every version by design. */
function pickerBlock(code, label) {
  const start = home.indexOf('      <div class="lang">');
  const end = home.indexOf('</div>', home.indexOf('</ul>', start)) + '</div>'.length;
  if (start < 0 || end < start) throw new Error('index.html: language picker not found');
  return [home.slice(start, end).trim(), langPicker(code, url, { label })];
}

/* Every relative reference becomes root-absolute, because the page moves from
   / to /de/. Doing it by prefixing '../' would work too, but root-absolute
   paths mean the same markup is correct at any depth, which matters once the
   route pages are generated in four languages as well. */
function reroot(s, code) {
  const b = code === 'en' ? '' : '/' + code;

  return s
    // assets live once, at the root, and are shared by all four versions
    .replace(/(\s(?:src|href)=")(images\/)/g, '$1/$2')
    // every URL in the list, not just the first: a srcset holds several,
    // and a half-rewritten one silently 404s the widths it did not touch
    .replace(/\s(srcset|imagesrcset)="([^"]*)"/g,
             (m, attr, val) => ' ' + attr + '="' + val.replace(/(^|,\s*)images\//g, '$1/images/') + '"')
    .replace(/(\s(?:src|href)=")(fonts\/)/g, '$1/$2')
    .replace(/url\('fonts\//g, "url('/fonts/")
    .replace(/(\ssrc=")consent\.js"/g, '$1/consent.js"')
    .replace(/fetch\('send-form\.php'/g, "fetch('/send-form.php'")
    // pages exist per language
    .replace(/(\shref=")routes\.html"/g, `$1${b}/routes.html"`)
    .replace(/(\shref=")routes\/([a-z0-9-]+)\.html"/g, `$1${b}/routes/$2.html"`)
    // the legal pages are German-law documents and are not translated, so all
    // four versions link to the one copy at the root
    .replace(/(\shref=")(impressum|datenschutz|agb)\.html"/g, '$1/$2.html"');
}

/* The runtime strings the page assembles in JavaScript. Only the UI map goes
   in — the homepage content is already baked into the markup above, and
   shipping it twice would double the page weight for nothing. */
function i18nBlob(code, ui, money) {
  const lang = byCode(code);
  return `<script>
  /* Strings the page builds at runtime (see T() / F() in the script below).
     Generated by build-i18n.mjs from i18n/ui.${code}.mjs — do not edit here. */
  window.RTA_LOCALE = ${JSON.stringify(lang.intl)};
  window.RTA_MONEY = ${JSON.stringify(money)};
  window.RTA_I18N = ${JSON.stringify(ui, null, 0)};
</script>
`;
}

/* Structured data: the prose inside it is translated with the same map, and the
   @id values keep pointing at the English graph so search engines treat the
   four versions as one entity rather than four competing businesses. */
function localizeJsonLd(s, map, code) {
  const open = '<script type="application/ld+json">';
  const i = s.indexOf(open);
  if (i < 0) throw new Error('index.html: JSON-LD block not found');
  const j = s.indexOf('</script>', i);
  const raw = s.slice(i + open.length, j);

  const data = JSON.parse(raw);
  const walk = (node) => {
    if (Array.isArray(node)) return node.map(walk);
    if (node && typeof node === 'object') {
      const out = {};
      for (const [k, v] of Object.entries(node)) out[k] = walk(v);
      return out;
    }
    if (typeof node === 'string' && Object.prototype.hasOwnProperty.call(map, node)) return map[node];
    return node;
  };

  const translated = walk(data);
  translated.inLanguage = byCode(code).intl;
  if (Array.isArray(translated['@graph'])) {
    for (const n of translated['@graph']) {
      if (n['@type'] === 'WebSite' || n['@type'] === 'WebPage') n.inLanguage = byCode(code).intl;
      if (n.url === SITE + '/') n.url = SITE + url(code);
    }
  }

  return s.slice(0, i + open.length) + JSON.stringify(translated) + s.slice(j);
}

let built = 0;
for (const lang of LANGS) {
  if (lang.code === 'en') continue;

  const { map, html: blocks } = await loadMap(lang.code);
  const ui = await loadUi(lang.code);
  const tpl = (await import(`./i18n/tpl.${lang.code}.mjs`)).default;
  const label = map['Change language'] || 'Change language';

  const r = localizePage(home, {
    map,
    html: [...blocks, pickerBlock(lang.code, label)],
  });

  if (r.missing.length) {
    console.error(`\n${lang.code}: ${r.missing.length} untranslated strings —`);
    r.missing.forEach((m) => console.error('   ' + JSON.stringify(m.slice(0, 110))));
    throw new Error(`${lang.code}: refusing to write a half-translated page`);
  }

  let s = r.html;

  s = s.replace('<html lang="en">', `<html lang="${lang.code}">`);
  s = s.replace(`<link rel="canonical" href="${SITE}/">`,
                `<link rel="canonical" href="${SITE}${url(lang.code)}">`);
  s = s.replace(`<meta property="og:url" content="${SITE}/">`,
                `<meta property="og:url" content="${SITE}${url(lang.code)}">`);
  s = s.replace('<meta property="og:locale" content="en_GB">',
                `<meta property="og:locale" content="${lang.locale}">` +
                LANGS.filter(l => l.code !== lang.code)
                     .map(l => `\n<meta property="og:locale:alternate" content="${l.locale}">`).join(''));

  s = localizeJsonLd(s, map, lang.code);
  s = reroot(s, lang.code);

  // the blob has to run before the script that reads it
  const mainScript = s.lastIndexOf('<script>');
  if (mainScript < 0) throw new Error('index.html: inline script not found');
  s = s.slice(0, mainScript) + i18nBlob(lang.code, ui, tpl.money(0).replace('0', '{n}')) + s.slice(mainScript);

  const out = outPath(lang.code, 'index.html');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, s);
  built++;
  console.log(`${out.padEnd(16)} ${(s.length / 1024).toFixed(0)} KB  ` +
              `${r.used.size} strings translated`);
}

console.log(`\nbuilt ${built} localized homepages`);
